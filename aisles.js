/* 買い物の売り場：材料名から決める（辞書 → 語尾・キーワード → 家庭ごとの直し）。
   並びはスーパーを回る順（青果→鮮魚→精肉→日配→卵・乳→主食→乾物・粉・缶詰→調味料・油→最後に冷凍）。 */
(function (root) {
  const AISLES = [
    ["veg", "🥬 野菜・果物"],
    ["fish", "🐟 魚"],
    ["meat", "🥩 肉"],
    ["daily", "🫘 日配（豆腐・納豆・練り物）"],
    ["chilled", "🥛 卵・乳製品"],
    ["staple", "🍚 米・麺・パン"],
    ["dry", "🥫 乾物・缶詰・粉"],
    ["seasoning", "🧂 調味料・油"],
    ["frozen", "🧊 冷凍"],
    ["other", "🛒 その他"],
  ];
  // きのこは青果売り場。以前の直し（mushroom）も青果として扱う。
  const LEGACY = { mushroom: "veg" };
  // 先に書いた規則が優先（例：鶏ガラスープの素→調味料、切り干し大根・干ししいたけ→乾物、梅干し→日配）。
  const RULES = [
    ["frozen", /^冷凍|冷凍食品|アイス/],
    ["dry", /缶$|缶詰|缶（|水煮缶|レトルト|ルウ$|ルー$|カレールー|シチュー|切り干し|干ししいたけ|干し椎茸|高野豆腐|乾燥|かつお節|削り節|塩昆布|のり$|焼きのり|味付けのり|海苔|わかめ|ひじき|昆布|パン粉|小麦粉|薄力粉|強力粉|米粉|片栗粉|天ぷら粉|から揚げ粉|お好み焼き粉|コーンスターチ|ベーキングパウダー|ゼラチン|ホットケーキ|ごま(?!油|だれ|ドレッシング)|胡麻(?!油|だれ)|ふりかけ|お茶漬け/],
    ["daily", /梅干し|紅しょうが|福神漬|たくあん|キムチ|漬物|ザーサイ|豆腐|厚揚げ|油揚げ|がんも|納豆|こんにゃく|しらたき|ちくわ|はんぺん|かまぼこ|かにかま|カニカマ|さつま揚げ|魚肉ソーセージ|餃子の皮|春巻きの皮|ワンタンの皮|シュウマイの皮|生麺|ゆで麺|ゆでうどん|蒸し中華麺|焼きそば麺|焼きそば用の中華麺/],
    ["seasoning", /チューブ|の素|顆粒|だし|出汁|コンソメ|ブイヨン|ソース|たれ|タレ|ドレッシング|(油|オイル)$|ポン酢|ぽん酢|味ぽん|めんつゆ|白だし|豆板醤|トウバンジャン|コチュジャン|甜麺醤|テンメンジャン|オイスター|ナンプラー|ラー油|チリソース|タバスコ|カレー粉|スパイス|花椒|山椒|一味|七味|柚子胡椒|ゆずこしょう|わさび|からし|マスタード|はちみつ|蜂蜜|マヨ|ケチャップ|ワイン|紹興酒/],
    ["chilled", /卵|たまご|玉子|牛乳|豆乳|ヨーグルト|チーズ|バター|マーガリン|生クリーム|ホイップ/],
    ["veg", /しめじ|えのき|まいたけ|舞茸|しいたけ|椎茸|エリンギ|マッシュルーム|なめこ|きのこ|キノコ/],
    ["meat", /肉|豚|鶏|牛|ひき|ミンチ|ささみ|手羽|レバー|砂肝|ホルモン|ベーコン|ハム|ウインナー|ソーセージ|チャーシュー|サラダチキン|ローストビーフ|ラム|鴨/],
    ["fish", /鮭|さけ|サーモン|さば|サバ|鯖|あじ|アジ|いわし|さんま|ぶり|ブリ|たら|タラ|鱈|まぐろ|マグロ|かつお|カツオ|たい|鯛|えび|エビ|海老|いか|イカ|たこ|タコ|ほたて|帆立|あさり|しじみ|牡蠣|かき|かに|カニ|蟹|しらす|ちりめん|明太子|たらこ|いくら|うなぎ|刺身|切り身|魚/],
    ["veg", /キャベツ|白菜|レタス|ほうれん草|ほうれんそう|小松菜|こまつな|はくさい|ちんげんさい|しゅんぎく|水菜|チンゲン|青梗菜|春菊|ニラ|にら|もやし|玉ねぎ|たまねぎ|玉葱|タマネギ|ねぎ|ネギ|葱|にんじん|人参|ニンジン|じゃがいも|ジャガイモ|さつまいも|里芋|長いも|長芋|大和芋|いも$|大根|だいこん|かぶ|ごぼう|れんこん|蓮根|トマト|きゅうり|キュウリ|胡瓜|なす|ナス|茄子|ピーマン|パプリカ|ブロッコリー|カリフラワー|アスパラ|オクラ|ズッキーニ|かぼちゃ|カボチャ|南瓜|とうもろこし|枝豆|えだまめ|いんげん|さやえんどう|絹さや|スナップ|豆苗|セロリ|みょうが|しそ|大葉|パセリ|バジル|パクチー|三つ葉|クレソン|ルッコラ|ベビーリーフ|サラダ菜|アボカド|レモン|ライム|りんご|バナナ|いちご|みかん|オレンジ|キウイ|ぶどう|梨|柿|しょうが|生姜|にんにく|ニンニク|ゆず|すだち|かいわれ|スプラウト|野菜|菜$/],
    ["staple", /米|ごはん|ご飯|パスタ|スパゲ|マカロニ|ペンネ|うどん|そば|蕎麦|そうめん|素麺|ひやむぎ|ラーメン|中華麺|焼きそば|食パン|(?<!フライ)パン(?!粉)|バゲット|トルティーヤ|はるさめ|春雨|ビーフン|フォー|もち|餅|オートミール|シリアル/],
    ["dry", /干し|粉$|ナッツ|くるみ|アーモンド|レーズン/],
    ["seasoning", /しょうゆ|醤油|塩|砂糖|みそ|味噌|みりん|酒|酢|こしょう|胡椒|ソルト|ペッパー|ハーブ|ローリエ|バジル（乾燥）/],
  ];
  const FROM_CATEGORY = { 野菜: "veg", 肉: "meat", 魚: "fish", 日配: "daily", 乾物: "dry", "大豆・卵・乳": "chilled", 主食: "staple", 調味料: "seasoning" };
  const baseName = (name) => String(name || "").normalize("NFKC").replace(/[（(][^）)]*[）)]/g, "").replace(/\s+/g, "").trim();

  function aisleOf(name, category = "", overrides = {}) {
    const raw = String(name || "").normalize("NFKC").trim();
    const key = baseName(name);
    const learned = LEGACY[overrides[key]?.aisle] || overrides[key]?.aisle;
    if (learned && AISLES.some(([id]) => id === learned)) return learned;
    if (/^冷凍|冷凍食品|[（(]冷凍/.test(raw)) return "frozen";
    if (/ベーキングパウダー/.test(key)) return "dry";
    if (/チューブ|(?:カレー|チリ|ガーリック|オニオン|パプリカ)パウダー/.test(raw)) return "seasoning";
    if (/はるさめ|春雨/.test(key) && /乾燥/.test(raw)) return "dry";
    if (/うどん|中華麺|そば|ラーメン/.test(key) && /ゆで|蒸し|生/.test(raw)) return "daily";
    for (const [id, re] of RULES) if (re.test(key)) return id;
    return FROM_CATEGORY[category] || "other";
  }

  // 調味料売り場の中の棚順（0: さしすせそ・酒・みりん → 1: 油・オイル → 2: つゆ・たれ・ソース・マヨ → 3: だし・中華・スパイス・チューブ）
  function seasoningShelfOrder(name) {
    const raw = String(name || "").normalize("NFKC");
    if (/(?:油|オイル)$/.test(raw) && !/ラー油|オイスター/.test(raw)) return 1;
    if (/塩|砂糖|しょうゆ|醤油|みそ|味噌|酢(?!豚)|みりん|料理酒|^酒$|日本酒|ワイン/.test(raw) && !/ポン酢|ぽん酢|塩昆布|オイスター/.test(raw)) return 0;
    if (/めんつゆ|白だし|ポン酢|ぽん酢|味ぽん|たれ|タレ|ソース|ケチャップ|マヨ|ドレッシング/.test(raw) && !/オイスター|チリソース/.test(raw)) return 2;
    return 3;
  }

  const aisleLabel = (id) => (AISLES.find((a) => a[0] === id) || AISLES[AISLES.length - 1])[1];
  const api = { AISLES, aisleOf, aisleLabel, baseName, seasoningShelfOrder };
  root.Aisles = api;
  if (typeof module !== "undefined") module.exports = api;
})(globalThis);
